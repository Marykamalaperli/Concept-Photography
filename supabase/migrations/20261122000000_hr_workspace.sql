create table concept.hr_settings (
  id integer primary key check (id = 1),
  work_start text,
  work_end text,
  week_off integer not null default 0 check (week_off between 0 and 6),
  monthly_leave integer not null default 2 check (monthly_leave between 0 and 31)
);
insert into concept.hr_settings (id) values (1);

create table concept.holidays (
  day text primary key, name text not null
);

create table concept.hr_requests (
  id integer generated by default as identity primary key,
  employee_id integer not null references concept.employees(id),
  kind text not null check (kind in ('leave', 'time')),
  day_from text not null, day_to text not null,
  leave_type text check (leave_type in ('casual', 'half', 'unpaid')),
  clock_in bigint, clock_out bigint,
  reason text not null, status text not null default 'pending' check (status in ('pending', 'approved', 'declined', 'cancelled')),
  requested_at bigint not null, decided_at bigint, decided_by integer references concept.employees(id)
);
create index hr_request_employee_days on concept.hr_requests (employee_id, day_from, day_to);

create table concept.work_logs (
  id integer generated by default as identity primary key,
  employee_id integer not null references concept.employees(id), day text not null,
  note text not null, minutes integer not null check (minutes between 0 and 1440), created_at bigint not null
);
create index work_log_employee_day on concept.work_logs (employee_id, day);

create table concept.payslips (
  id integer generated by default as identity primary key,
  employee_id integer not null references concept.employees(id),
  period text not null, gross_paise bigint not null check (gross_paise >= 0), deductions_paise bigint not null,
  note text, published_at bigint not null, unique (employee_id, period),
  check (deductions_paise between 0 and gross_paise)
);

create table concept.announcements (
  id integer generated by default as identity primary key,
  title text not null, message text not null, published_at bigint not null
);

