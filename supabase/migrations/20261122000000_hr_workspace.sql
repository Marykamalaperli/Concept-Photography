drop trigger update_task_calendar_version on concept.tasks;
create trigger update_task_calendar_version
before update of title, employee_id, start_at, estimate, location, priority, is_open, shoot_status on concept.tasks
for each row when (
  row(old.title, old.employee_id, old.start_at, old.estimate, old.location, old.priority, old.is_open, old.shoot_status)
  is distinct from row(new.title, new.employee_id, new.start_at, new.estimate, new.location, new.priority, new.is_open, new.shoot_status)
)
execute function concept.update_task_calendar_version();

create table concept.shoot_crew (
  task_id integer not null references concept.tasks(id) on delete cascade,
  employee_id integer not null references concept.employees(id),
  primary key (task_id, employee_id)
);
create index shoot_crew_employee on concept.shoot_crew (employee_id, task_id);
alter table concept.shoot_crew enable row level security;
revoke all on concept.shoot_crew from public, anon, authenticated, service_role;

create view concept.task_assignments as
  select id as task_id, employee_id from concept.tasks where is_open = 0
  union
  select shoot_crew.task_id, shoot_crew.employee_id from concept.shoot_crew
    join concept.tasks on tasks.id = shoot_crew.task_id where tasks.is_open = 0;
revoke all on concept.task_assignments from public, anon, authenticated, service_role;

