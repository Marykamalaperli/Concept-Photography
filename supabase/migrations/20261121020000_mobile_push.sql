create table concept.push_settings (
  id integer primary key check (id = 1),
  cron_token text not null default replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''),
  dispatch_url text,
  vapid_public_key text,
  vapid_private_key text,
  last_dispatch_at bigint
);
insert into concept.push_settings (id) values (1);

create table concept.push_subscriptions (
  id integer generated by default as identity primary key,
  employee_id integer not null references concept.employees(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth_secret text not null
);
create index push_subscriptions_employee on concept.push_subscriptions (employee_id);

create table concept.push_deliveries (
  task_id integer not null references concept.tasks(id) on delete cascade,
  employee_id integer not null references concept.employees(id) on delete cascade,
  start_at bigint not null,
  subscription_id integer not null references concept.push_subscriptions(id) on delete cascade,
  attempts integer not null default 0,
  next_attempt_at bigint not null,
  sent_at bigint,
  primary key (task_id, employee_id, start_at, subscription_id)
);
create index push_deliveries_due on concept.push_deliveries (next_attempt_at) where sent_at is null;

alter table concept.push_settings enable row level security;
alter table concept.push_subscriptions enable row level security;
alter table concept.push_deliveries enable row level security;
revoke all on concept.push_settings, concept.push_subscriptions, concept.push_deliveries
from public, anon, authenticated, service_role;
revoke all on sequence concept.push_subscriptions_id_seq from public, anon, authenticated, service_role;
