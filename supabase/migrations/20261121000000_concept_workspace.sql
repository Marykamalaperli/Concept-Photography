-- Keep the workspace outside Supabase's public Data API schema.
create schema concept;
revoke all on schema concept from public, anon, authenticated, service_role;

create table concept.employees (
  id integer generated by default as identity primary key,
  name text not null, role text not null, email text not null unique, color text not null,
  is_admin integer not null default 0, phone text, password_hash text, archived integer not null default 0
);

create unique index one_workspace_admin on concept.employees (is_admin)
  where is_admin = 1 and archived = 0;

create table concept.office (
  id integer primary key check (id = 1),
  name text not null, latitude double precision not null, longitude double precision not null, maps_url text
);

create table concept.clients (
  id integer generated by default as identity primary key,
  name text not null, phone text not null unique, email text, notes text
);

create table concept.tasks (
  id integer generated by default as identity primary key,
  title text not null, employee_id integer not null references concept.employees(id),
  start_at bigint not null, estimate integer not null, location text not null,
  category text not null, completed_at bigint,
  site_latitude double precision, site_longitude double precision, maps_url text,
  client_id integer references concept.clients(id),
  income_paise bigint not null default 0 check (income_paise >= 0),
  priority integer not null default 0, is_open integer not null default 0
);

create table concept.task_sessions (
  id integer generated by default as identity primary key,
  task_id integer not null references concept.tasks(id),
  employee_id integer not null references concept.employees(id), start_at bigint not null, end_at bigint
);

create unique index one_active_task on concept.task_sessions (employee_id) where end_at is null;

create table concept.attendance (
  id integer generated by default as identity primary key,
  employee_id integer not null references concept.employees(id),
  clock_in bigint not null, clock_out bigint, in_location text not null, out_location text,
  site text, in_reason text not null default 'manual', out_reason text, resume_pending integer not null default 0
);

create unique index one_active_shift on concept.attendance (employee_id) where clock_out is null;

create table concept.reminders (
  task_id integer primary key references concept.tasks(id),
  employee_id integer not null references concept.employees(id), sent_at bigint not null, read_at bigint
);

create table concept.auth_sessions (
  token_hash text primary key, employee_id integer not null references concept.employees(id), expires_at bigint not null
);

create table concept.login_limits (
  key text primary key, count integer not null, reset_at bigint not null
);

create table concept.work_requests (
  id integer generated by default as identity primary key,
  task_id integer not null references concept.tasks(id), employee_id integer not null references concept.employees(id),
  note text, requested_at bigint not null,
  status text not null check (status in ('pending', 'approved', 'declined')),
  decided_at bigint, unique (task_id, employee_id)
);

create table concept.payments (
  id integer generated by default as identity primary key,
  task_id integer not null references concept.tasks(id),
  amount_paise bigint not null check (amount_paise > 0), paid_on text not null, note text
);

create table concept.expenses (
  id integer generated by default as identity primary key,
  name text not null, category text not null,
  amount_paise bigint not null check (amount_paise > 0), spent_on text not null, note text
);

create index task_employee_date on concept.tasks (employee_id, start_at);
create index attendance_employee_date on concept.attendance (employee_id, clock_in desc);
create index payment_task on concept.payments (task_id);
create index expiration_sessions on concept.auth_sessions (expires_at);
create index expiration_login_limits on concept.login_limits (reset_at);

revoke all on all tables in schema concept from public, anon, authenticated, service_role;
revoke all on all sequences in schema concept from public, anon, authenticated, service_role;

alter table concept.employees enable row level security;
alter table concept.office enable row level security;
alter table concept.clients enable row level security;
alter table concept.tasks enable row level security;
alter table concept.task_sessions enable row level security;
alter table concept.attendance enable row level security;
alter table concept.reminders enable row level security;
alter table concept.auth_sessions enable row level security;
alter table concept.login_limits enable row level security;
alter table concept.work_requests enable row level security;
alter table concept.payments enable row level security;
alter table concept.expenses enable row level security;
